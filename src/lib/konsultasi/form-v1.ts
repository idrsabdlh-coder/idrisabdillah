/** Helper pembentuk opsi standar dari label. */
const o = (label: string, extra?: Omit<Opsi, "nilai" | "label">): Opsi => ({
  nilai: slug(label),
  label,
  ...extra,
});

/** Opsi yang menandakan klien butuh bantuan/rekomendasi tim (FR-KON-09). */
const bantuan = (label: string, extra?: Omit<Opsi, "nilai" | "label" | "butuhBantuan">): Opsi =>
  o(label, { butuhBantuan: true, ...extra });

